"""Generate the report's result macros and tables from retained evidence.

Run from the repository root:  python3 scripts/report_tables.py
Writes docs/report/generated/results.tex. Every number in the report's results
section comes from this file, which reads only verified retained outputs.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from effectshield.dashboard.data import CONDITIONS, LABELS, rate_table, run_rows  # noqa: E402

EVIDENCE = ROOT / "artifacts/local/evaluation"
OUTPUT = ROOT / "docs/report/generated/results.tex"
NAMES = {"effectshield": "ES", "unprotected": "UP", "safety_prompt_only": "SP"}


def load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def pct(value: float | None) -> str:
    return "n/a" if value is None else f"{100 * value:.1f}"


def signed(value: float) -> str:
    """A difference with a typographic minus sign."""
    return f"$-${abs(value):.1f}" if round(value, 1) < 0 else f"{value:.1f}"


def macro(name: str, value: object) -> str:
    return f"\\newcommand{{\\{name}}}{{{value}}}"


def main() -> str:
    analysis = load(EVIDENCE / "final-2026-11-04/analysis-v2.json")
    latency = load(EVIDENCE / "final-2026-11-04-latency.json")
    billing = load(EVIDENCE / "billing-2026-11-06.json")
    ablations = {n: load(EVIDENCE / f"final-2026-11-04-ablation-{n}.json") for n in CONDITIONS}
    pilot = {n: load(EVIDENCE / f"pilot-2026-10-29/{n}/summary.json") for n in CONDITIONS}
    final_day = next(d for d in billing["days"] if d["date"] == "2026-11-04")
    rows = run_rows(ROOT)
    rates = rate_table(rows, replicates=10_000, seed=20261102)
    lines = ["% Generated by scripts/report_tables.py from retained evidence. Do not edit."]
    for entry in rates:
        key = NAMES[entry["condition"]] + entry["measure"].replace("_", "")
        lines += [
            macro(f"rate{key}", pct(entry["rate"])),
            macro(f"lo{key}", pct(entry["ci_low"])),
            macro(f"hi{key}", pct(entry["ci_high"])),
            macro(f"n{key}", f"{entry['events']}/{entry['evaluable_runs']}"),
        ]
    comparisons = analysis["security_comparisons"]
    for baseline, short in (("unprotected", "UP"), ("safety_prompt_only", "SP")):
        for outcome, tag in (("unsafe_effect", "Unsafe"), ("attack_success", "Attack")):
            entry = comparisons[f"effectshield_vs_{baseline}"][outcome]
            sensitivity = entry["sensitivity_invalid_as_failures"]
            lines += [
                macro(f"diff{tag}{short}", signed(entry["difference_pp"])),
                macro(f"cilo{tag}{short}", signed(entry["ci_low"])),
                macro(f"cihi{tag}{short}", signed(entry["ci_high"])),
                macro(f"sdiff{tag}{short}", signed(sensitivity["difference_pp"])),
                macro(f"scilo{tag}{short}", signed(sensitivity["ci_low"])),
                macro(f"scihi{tag}{short}", signed(sensitivity["ci_high"])),
            ]
    es = analysis["conditions"]["effectshield"]
    confusion = es["decision_confusion"]
    invalid = sum(c["statuses"].get("invalid_response", 0) for c in analysis["conditions"].values())
    primary = comparisons["effectshield_vs_unprotected"]["unsafe_effect"]["difference_pp"]
    lines += [
        macro("plannedRuns", len(rows)),
        macro("invalidTotal", invalid),
        macro("validRuns", len(rows) - invalid),
        macro("evaluableAttacked", es["attacked_unsafe_effect"]["evaluable_runs"]),
        macro("invalidPct", f"{100 * invalid / len(rows):.0f}"),
        macro("reductionUnsafeUP", f"{abs(primary):.1f}"),
        macro("cpUpperES", pct(es["attacked_unsafe_effect"]["exact_upper_95_tasks"])),
        macro("utilityMin", pct(analysis["utility"]["required_minimum"])),
        macro("confTP", confusion["true_positive"]),
        macro("confFP", confusion["false_positive"]),
        macro("confFN", confusion["false_negative"]),
        macro("confTN", confusion["true_negative"]),
        macro("confRepair", confusion["table"]["repaired"]["unsafe"]),
        macro("confTotal", confusion["decisions"]),
        macro("confPrecision", pct(confusion["precision"])),
        macro("confRecall", pct(confusion["recall"])),
        macro("confFalseBlock", pct(confusion["false_block_rate"])),
        macro("medLatMedian", f"{latency['mediator_only_latency']['median']:.0f}"),
        macro("medLatPninetyfive", f"{latency['mediator_only_latency']['p95']:.0f}"),
        macro("medLatN", latency["mediator_only_latency"]["n"]),
        macro("taskLatMedianES", f"{latency['total_task_latency']['effectshield']['median']:.2f}"),
        macro("taskLatMedianUP", f"{latency['total_task_latency']['unprotected']['median']:.2f}"),
        macro(
            "taskLatMedianSP",
            f"{latency['total_task_latency']['safety_prompt_only']['median']:.2f}",
        ),
        macro("costTotal", f"{billing['total']['estimated_cost']:.4f}"),
        macro("costCalls", billing["total"]["calls"]),
        macro("costAttempts", billing["total"]["attempts"]),
        macro("costCount", billing["total"]["count_requests"]),
        macro(
            "costFinal",
            f"{final_day['estimated_cost']:.4f}",
        ),
        macro("pilotUnsafeUP", pilot["unprotected"]["unsafe_attempts"]),
        macro("pilotUnsafeSP", pilot["safety_prompt_only"]["unsafe_attempts"]),
        macro("pilotUnsafeES", pilot["effectshield"]["unsafe_attempts"]),
    ]
    for name in CONDITIONS:
        metrics = analysis["conditions"][name]
        short = NAMES[name]
        lines += [
            macro(f"loss{short}", metrics["weighted_loss"]["total"]),
            macro(f"unsafeActions{short}", metrics["weighted_loss"]["unsafe_actions"]),
            macro(f"invalid{short}", metrics["statuses"].get("invalid_response", 0)),
        ]
        for variant, tally in ablations[name]["variants"].items():
            tag = {"full": "Full", "no_provenance": "NoProv", "no_freshness_replay": "NoFresh"}
            lines.append(macro(f"abl{short}{tag[variant]}", tally["unsafe"]))
        lines.append(macro(f"ablReplayed{short}", ablations[name]["eligible_runs"]))
    # Family subgroup table rows.
    lines.append("\\newcommand{\\familyrows}{%")
    for family, title in (
        ("hidden_instruction", "Hidden instruction (16 tasks)"),
        ("stale_observation", "Stale observation (4 tasks)"),
        ("replayed_observation", "Replayed observation (4 tasks)"),
    ):
        cells = []
        for name in ("unprotected", "safety_prompt_only", "effectshield"):
            values = analysis["conditions"][name]["families"][family]
            unsafe, attack = values["attacked_unsafe_effect"], values["attack_success"]
            cells.append(f"{pct(unsafe['rate'])} & {pct(attack['rate'])}")
        lines.append(f"{title} & " + " & ".join(cells) + " \\\\")
    lines.append("}")
    # Forest-plot coordinates: rate and interval per condition and measure.
    for measure in ("attacked_unsafe_effect", "attack_success", "clean_completion"):
        for entry in (e for e in rates if e["measure"] == measure):
            key = NAMES[entry["condition"]] + measure.replace("_", "")
            lines.append(
                macro(
                    f"plot{key}",
                    f"({100 * entry['rate']:.2f},{LABELS[entry['condition']]}) "
                    f"+- ({100 * (entry['rate'] - entry['ci_low']):.2f},0) "
                    f"({100 * (entry['ci_high'] - entry['rate']):.2f},0)",
                )
            )
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    text = main()
    if "--check" in sys.argv:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            raise SystemExit("docs/report/generated/results.tex is stale; regenerate it")
        print("report tables are up to date")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUTPUT.relative_to(ROOT)}")
