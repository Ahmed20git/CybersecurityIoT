"""Write the demo script and, optionally, record the narrated dashboard demonstration.

Usage, from the repository root:
  python3 scripts/record_demo.py --script            # writes docs/demo/demo_script.md
  python3 scripts/record_demo.py --record OUT_DIR    # narrated MP4 + SRT of the live dashboard

Recording needs a running dashboard (streamlit run src/effectshield/dashboard/app.py on
--url), Playwright with Chromium (a separate tool, not a project dependency), ffmpeg and
macOS `say`. Narration numbers are filled from retained evidence, never typed by hand.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from effectshield.dashboard.data import load_study  # noqa: E402

SEGMENTS = ROOT / "docs/demo/segments.json"
SCRIPT = ROOT / "docs/demo/demo_script.md"
VOICE, RATE = "Samantha", 172
WORDS_PER_SECOND = 2.75  # estimate used only when no audio has been generated


def spoken(value: float) -> str:
    text = f"{abs(value):.1f}".removesuffix(".0")
    return ("minus " if value < 0 else "") + text


def facts() -> dict[str, str]:
    study = load_study(ROOT)
    analysis, latency, billing = study["analysis"], study["latency"], study["billing"]
    conditions = analysis["conditions"]
    primary = analysis["security_comparisons"]["effectshield_vs_unprotected"]["unsafe_effect"]

    def runs(name: str) -> str:
        m = conditions[name]["attacked_unsafe_effect"]
        return f"{m['successes']} of {m['evaluable_runs']}"

    return {
        "planned_runs": str(study["provenance"]["planned_runs"]),
        "model": "GPT 4.1 mini",
        "es_unsafe_runs": runs("effectshield"),
        "up_unsafe_runs": runs("unprotected"),
        "sp_unsafe_runs": runs("safety_prompt_only"),
        "primary_diff": spoken(primary["difference_pp"]),
        "primary_low": spoken(primary["ci_low"]),
        "primary_high": spoken(primary["ci_high"]),
        "es_clean": spoken(100 * conditions["effectshield"]["clean_completion"]["rate"]),
        "up_clean": spoken(100 * conditions["unprotected"]["clean_completion"]["rate"]),
        "false_blocks": str(conditions["effectshield"]["decision_confusion"]["false_positive"]),
        "ablation_no_freshness": str(
            study["ablations"]["unprotected"]["variants"]["no_freshness_replay"]["unsafe"]
        ),
        "latency_us": str(round(latency["mediator_only_latency"]["median"])),
        "task_s": spoken(latency["total_task_latency"]["effectshield"]["median"]),
        "cost": f"{billing['total']['estimated_cost']:.2f}",
        "invalid": "97",
    }


def segments() -> list[dict[str, Any]]:
    document = json.loads(SEGMENTS.read_text(encoding="utf-8"))
    values = facts()
    for segment in document["segments"]:
        segment["text"] = segment["narration"].format(**values)
    return list(document["segments"])


def timestamp(seconds: float, *, srt: bool = False) -> str:
    minutes, rest = divmod(seconds, 60)
    hours, minutes = divmod(int(minutes), 60)
    if srt:
        return f"{hours:02d}:{minutes:02d}:{rest:06.3f}".replace(".", ",")
    return f"{minutes}:{int(rest):02d}"


def write_script(
    parts: list[dict[str, Any]], starts: list[float] | None = None, end: float | None = None
) -> None:
    """Write the script; with a recording, use its measured segment starts and length."""
    lines = [
        "# EffectShield five-minute demonstration",
        "",
        "Generated by `scripts/record_demo.py --script` from `docs/demo/segments.json` and the "
        "retained evidence. Each segment shows the dashboard page named; the narration is what "
        "the presenter says (or the recorded voice-over).",
        "",
        "| Time | Dashboard page | On screen | Narration |",
        "| --- | --- | --- | --- |",
    ]
    clock = 0.0
    for index, part in enumerate(parts):
        if starts:
            clock = starts[index]
        actions = (
            "; ".join(
                f"scroll to “{a['scroll_to']}”"
                if "scroll_to" in a
                else f"select {a['select']['label']} = {a['select']['option']}"
                for a in part["actions"]
            )
            or "page as loaded"
        )
        page = part["page"] or "overview"
        lines.append(f"| {timestamp(clock)} | {page} | {actions} | {part['text']} |")
        clock += len(part["text"].split()) / WORDS_PER_SECOND + 0.6
    total = end if end is not None else clock
    lines += ["", f"Total running time: about {timestamp(total)}.", ""]
    SCRIPT.write_text("\n".join(lines), encoding="utf-8")


def narrate(parts: list[dict[str, Any]], out: Path) -> list[float]:
    durations = []
    for index, part in enumerate(parts):
        audio = out / f"segment-{index:02d}.aiff"
        subprocess.run(
            ["say", "-v", VOICE, "-r", str(RATE), "-o", str(audio), part["text"]], check=True
        )
        probe = subprocess.run(
            [
                "ffprobe",
                "-v",
                "error",
                "-show_entries",
                "format=duration",
                "-of",
                "csv=p=0",
                str(audio),
            ],
            check=True,
            capture_output=True,
            text=True,
        )
        durations.append(float(probe.stdout.strip()))
    return durations


def wait_ready(page: Any) -> None:
    page.wait_for_selector('[data-testid="stMain"]', timeout=180_000)
    quiet = 0
    while quiet < 3:
        time.sleep(0.4)
        quiet = quiet + 1 if page.locator('[data-testid="stStatusWidget"]').count() == 0 else 0


def scroll_to(page: Any, text: str) -> None:
    page.evaluate(
        """(text) => {
            const nodes = [...document.querySelectorAll('h1,h2,h3,h4,p,span,div')];
            const node = nodes.find(n => n.childElementCount === 0 && n.textContent.includes(text));
            if (node) node.scrollIntoView({behavior: 'smooth', block: 'start'});
        }""",
        text,
    )


def select(page: Any, label: str, option: str) -> None:
    """Pick an option in a Streamlit select box (a React Aria combo box)."""
    box = page.locator(f'input[role="combobox"][aria-label="{label}"]')
    box.click()
    time.sleep(0.3)
    box.press("Meta+A")
    box.type(option, delay=45)
    time.sleep(0.5)
    page.locator('[role="option"]').filter(has_text=option).first.click()
    wait_ready(page)
    if box.input_value() != option:
        raise RuntimeError(f"Could not select {option!r} in {label!r}")


def record(parts: list[dict[str, Any]], out: Path, url: str) -> Path:
    from playwright.sync_api import sync_playwright

    out.mkdir(parents=True, exist_ok=True)
    durations = narrate(parts, out)
    starts: list[float] = []
    with sync_playwright() as playwright:
        browser = playwright.chromium.launch()
        context = browser.new_context(
            viewport={"width": 1920, "height": 1080},
            record_video_dir=str(out),
            record_video_size={"width": 1920, "height": 1080},
        )
        origin = time.monotonic()
        page = context.new_page()
        current = None
        for part, duration in zip(parts, durations, strict=True):
            if part["page"] != current:
                page.goto(f"{url}/{part['page']}")
                wait_ready(page)
                current = part["page"]
            start = time.monotonic() - origin
            starts.append(start)
            for action in sorted(part["actions"], key=lambda a: a["at"]):
                delay = start + action["at"] * duration - (time.monotonic() - origin)
                if delay > 0:
                    time.sleep(delay)
                if "scroll_to" in action:
                    scroll_to(page, action["scroll_to"])
                else:
                    select(page, action["select"]["label"], action["select"]["option"])
            remaining = start + duration + 0.6 - (time.monotonic() - origin)
            if remaining > 0:
                time.sleep(remaining)
        video = Path(page.video.path())
        context.close()
        browser.close()
    offset = starts[0]
    subtitles = out / "effectshield_demo.srt"
    entries = []
    for index, (part, start, duration) in enumerate(zip(parts, starts, durations, strict=True)):
        begin, end = start - offset, start - offset + duration
        entries.append(
            f"{index + 1}\n{timestamp(begin, srt=True)} --> "
            f"{timestamp(end, srt=True)}\n{part['text']}\n"
        )
    subtitles.write_text("\n".join(entries), encoding="utf-8")
    inputs = ["-ss", f"{offset:.3f}", "-i", str(video)]
    filters, labels = [], []
    for index, start in enumerate(starts):
        inputs += ["-i", str(out / f"segment-{index:02d}.aiff")]
        delay = int(round((start - offset) * 1000))
        filters.append(f"[{index + 1}:a]adelay={delay}|{delay}[a{index}]")
        labels.append(f"[a{index}]")
    filters.append("".join(labels) + f"amix=inputs={len(starts)}:normalize=0[voice]")
    final = out / "effectshield_demo.mp4"
    subprocess.run(
        [
            "ffmpeg",
            "-y",
            "-loglevel",
            "error",
            *inputs,
            "-i",
            str(subtitles),
            "-filter_complex",
            ";".join(filters),
            "-map",
            "0:v",
            "-map",
            "[voice]",
            "-map",
            f"{len(starts) + 1}:s",
            "-c:v",
            "libx264",
            "-preset",
            "slow",
            "-crf",
            "20",
            "-pix_fmt",
            "yuv420p",
            "-c:a",
            "aac",
            "-b:a",
            "160k",
            "-c:s",
            "mov_text",
            "-shortest",
            "-metadata",
            "title=EffectShield results demonstration",
            str(final),
        ],
        check=True,
    )
    write_script(parts, [start - offset for start in starts], starts[-1] - offset + durations[-1])
    return final


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--script", action="store_true", help="Write docs/demo/demo_script.md")
    parser.add_argument("--record", type=Path, help="Directory for the narrated recording")
    parser.add_argument("--url", default="http://localhost:8765")
    args = parser.parse_args()
    parts = segments()
    if args.record:
        print(record(parts, args.record, args.url))
    else:
        write_script(parts)
        print(SCRIPT.relative_to(ROOT))


if __name__ == "__main__":
    main()
